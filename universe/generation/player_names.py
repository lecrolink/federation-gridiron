JOE_GIVEN_INDEX = 140

def _check_lists():
    if len(GIVEN_NAMES) != 250 or len(set(GIVEN_NAMES)) != 250:
        raise RuntimeError('The approved given-name list is 250 unique names.')
    if GIVEN_NAMES != tuple(sorted(GIVEN_NAMES)):
        raise RuntimeError('Given names must stay in Python alphabetical order.')
    if GIVEN_NAMES[JOE_GIVEN_INDEX] != 'Joe':
        raise RuntimeError('Joe must stay at given-name index 140.')
    if any(name in GIVEN_NAMES for name in ('Joseph', 'Joey', 'Kermit')):
        raise RuntimeError('Joseph, Joey, and Kermit stay off the given-name list.')
    if len(SURNAMES) != 1000 or len(set(SURNAMES)) != 1000:
        raise RuntimeError('The approved surname list is 1,000 unique names.')
    if SURNAMES != tuple(sorted(SURNAMES)):
        raise RuntimeError('Surnames must stay in Python alphabetical order.')
    if 'LeCrone' in SURNAMES or 'LeCrone' in GIVEN_NAMES:
        raise RuntimeError('LeCrone stays off both player name lists.')
    if len(COLLEGES) != 64 or len({row[1] for row in COLLEGES}) != 64:
        raise RuntimeError('The frozen college corpus is 64 schools.')


_check_lists()
